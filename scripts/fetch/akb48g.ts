export function getAKB48GroupMembers(): Member[] {
  return AKB48G_SEEDS.map((seed) => {
    const id = toSlug(seed.groupId, seed.kana);
    const romajiName = seed.romaji || formatPersonRomaji(seed.kana);
    const hangulName = seed.hangul || kanaToHangul(seed.kana);
    const avatar = generateAvatar(id, seed.kanji);

    const links: MemberLink[] = (seed.sns || []).map((s) => ({
      type: s.type as MemberLink['type'],
      url: s.url as MemberLink['url'],
      label: null,
      isOfficial: true,
      status: 'ok',
      lastCheckedAt: '2026-08-16',
      lastStatusCode: 200,
    }));

    return {
      id,
      name: {
        ja: {
          kanji: seed.kanji,
          kana: seed.kana,
        },
        ko: {
          hangul: hangulName,
        },
        en: {
          romaji: romajiName,
        },
        aliases: [romajiName.toLowerCase(), seed.kanji, hangulName],
      },
      primaryGroupId: seed.groupId,
      primaryGenerationId: seed.genId,
      status: seed.status || 'active',
      memberships: [
        {
          groupId: seed.groupId,
          generationId: seed.genId,
          joinedOn: seed.joinedOn,
          leftOn: seed.leftOn ?? null,
          isConcurrent: false,
          endReason: seed.status === 'graduated' ? 'graduation' : null,
        },
      ],
      birthDate: seed.birthDate || null,
      birthplace: null,
      officialCode: seed.code || null,
      imageUrl: null,
      links,
      avatar,
      provenance: {
        source: 'official',
        sourceUrl: seed.sns?.[0]?.url || 'https://www.akb48.co.jp/',
        checkedAt: '2026-08-16',
        note: 'AKB48 Group seed dataset',
      },
    };
  });
}
